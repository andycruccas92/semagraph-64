// Generates the trajectory shape/projection parity fixture.
//
// Output: packages/core-rs/tests/fixtures/shape-parity.json
//
// The fixture is produced by the TypeScript reference implementation in
// `@semagraph-64/kernel`'s `shapes.ts` and is the authority the Rust batch port
// (`packages/core-rs/src/shapes.rs`) is checked against. For each Q3 trajectory
// it records the run-collapsed shape, the dwell vector, and the declared lossy
// projections (net mutation, endpoint code, endpoint Hamming distance) plus the
// cumulative traversal distance, so the Rust parity test can compare on integers
// without any string mapping.
//
// Determinism: the random trajectories are drawn from a seeded mulberry32 PRNG.
// The seed is recorded in the fixture. Re-running this script reproduces the
// committed file byte-for-byte (CI enforces this with `git diff --exit-code`).
//
// Run with: node packages/state64-adapter/scripts/generate-shape-parity-fixture.mjs

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  cumulativeDistanceQ3,
  endpointCompression,
  endpointHammingDistance,
  netMutationQ3,
  normalizePathRunCollapse,
  pathQ3
} from "@semagraph-64/kernel";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, "../../core-rs/tests/fixtures/shape-parity.json");

const SEED = 0x5e3a9c01;

// mulberry32: a tiny, fully deterministic 32-bit PRNG. Same seed => same stream
// on every platform, which is what keeps this fixture reproducible.
function mulberry32(seed) {
  let state = seed >>> 0;
  return function next() {
    state = (state + 0x6d2b79f5) >>> 0;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rng = mulberry32(SEED);
const randInt = (maxExclusive) => Math.floor(rng() * maxExclusive);

// Hand-picked edge cases that exercise the run-collapse and projection rules.
const handPicked = [
  [0], //                    single state: no steps, dwell [1]
  [3, 3, 3, 3], //           all identical: collapses to one run, dwell [4]
  [0, 1, 1, 3], //           adjacent duplicate collapses
  [0, 1, 0, 3], //           non-adjacent return is preserved (NOT collapsed)
  [0, 4, 6, 2], //           net mutation differs from cumulative distance
  [0, 7, 0], //              out-and-back: net mutation 0, cumulative 6
  [7, 7, 0, 0, 7, 7], //     two runs of 7 separated by a run of 0
  [0, 1, 2, 3, 4, 5, 6, 7], // every elementary state once
  [5, 2], //                 minimal two-state path
  [2, 2, 5, 5, 5, 2] //      run lengths 2,3,1
];

const trajectories = [...handPicked];

// Seeded random trajectories of length 1..16 over Q3 (0..7).
const RANDOM_COUNT = 240;
for (let i = 0; i < RANDOM_COUNT; i += 1) {
  const length = 1 + randInt(16);
  const states = [];
  for (let j = 0; j < length; j += 1) states.push(randInt(8));
  trajectories.push(states);
}

const entries = trajectories.map((states) => {
  const path = pathQ3(states);
  const normalized = normalizePathRunCollapse(path);
  return {
    states,
    shape: [...normalized.shape],
    dwell: [...normalized.dwell],
    netMutation: netMutationQ3(path),
    endpointCode: endpointCompression(path),
    endpointHamming: endpointHammingDistance(path),
    cumulativeDistance: cumulativeDistanceQ3(path)
  };
});

const fixture = {
  description:
    "Q3 trajectory shape/projection parity fixture generated by the TypeScript reference (kernel/shapes.ts).",
  generator: "packages/state64-adapter/scripts/generate-shape-parity-fixture.mjs",
  seed: SEED,
  trajectoryCount: entries.length,
  entries
};

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`Wrote ${entries.length} trajectory projections to ${outPath}`);
