// Generates the exhaustive cross-implementation parity fixture.
//
// Output: packages/core-rs/tests/fixtures/transition-parity.json
//
// The fixture is produced by the TypeScript reference implementation and is the
// authority the Rust core is checked against. It lists all 64 x 64 = 4096
// transitions with the canonical integer codes and the packed 64-bit FFI word,
// so the Rust parity test can compare on integers without any string mapping.
//
// Run with: node packages/state64-adapter/scripts/generate-parity-fixture.mjs

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  STATE64_MODULE_SCOPE_CODE,
  STATE64_REGIME_CLASS_CODE,
  classifyState64RegimePair,
  createState64FromNumber,
  transitionIndex64Number
} from "../dist/index.js";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(here, "../../core-rs/tests/fixtures/transition-parity.json");

function popcount6(value) {
  let count = 0;
  for (let bit = 0; bit < 6; bit += 1) count += (value >> bit) & 1;
  return count;
}

// Mirrors `pack_transition64` in packages/core-rs/src/lib.rs.
// Uses BigInt because the index field is shifted left by 30 bits.
function packTransition({ source, target, mutationMask, distance, lowerDistance, upperDistance, moduleScopeCode, regimeClassCode, index }) {
  let packed = 0n;
  packed |= BigInt(source) & 0x3fn;
  packed |= (BigInt(target) & 0x3fn) << 6n;
  packed |= (BigInt(mutationMask) & 0x3fn) << 12n;
  packed |= (BigInt(distance) & 0x07n) << 18n;
  packed |= (BigInt(lowerDistance) & 0x03n) << 21n;
  packed |= (BigInt(upperDistance) & 0x03n) << 23n;
  packed |= (BigInt(moduleScopeCode) & 0x03n) << 25n;
  packed |= (BigInt(regimeClassCode) & 0x07n) << 27n;
  packed |= (BigInt(index) & 0x0fffn) << 30n;
  return packed;
}

const entries = [];
for (let source = 0; source < 64; source += 1) {
  for (let target = 0; target < 64; target += 1) {
    const mutationMask = source ^ target;
    const lowerMask = (mutationMask >> 3) & 0b111;
    const upperMask = mutationMask & 0b111;
    const classification = classifyState64RegimePair(createState64FromNumber(source), createState64FromNumber(target));
    const moduleScopeCode = STATE64_MODULE_SCOPE_CODE[classification.moduleScope];
    const regimeClassCode = STATE64_REGIME_CLASS_CODE[classification.regimeClass];
    const record = {
      source,
      target,
      mutationMask,
      distance: popcount6(mutationMask),
      lowerDistance: popcount6(lowerMask),
      upperDistance: popcount6(upperMask),
      moduleScopeCode,
      regimeClassCode,
      index: transitionIndex64Number(source, target)
    };
    record.packed = packTransition(record).toString();
    entries.push(record);
  }
}

const fixture = {
  description: "Exhaustive State64 transition parity fixture generated by the TypeScript reference implementation.",
  generator: "packages/state64-adapter/scripts/generate-parity-fixture.mjs",
  stateCount: 64,
  transitionCount: entries.length,
  entries
};

mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, `${JSON.stringify(fixture, null, 2)}\n`);
console.log(`Wrote ${entries.length} transitions to ${outPath}`);
